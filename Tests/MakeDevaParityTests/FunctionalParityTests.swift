/// Resolves `samples/` for parity tests: env override, then walk up from this file toward repo root.
private func resolveParitySamplesDirectory(file: String = #filePath) -> String {
    if let env = ProcessInfo.processInfo.environment["MAKEDEVA_SAMPLES_PATH"],
       FileManager.default.fileExists(atPath: "\(env)/LT/expected")
    {
        return env
    }

    var url = URL(fileURLWithPath: file).deletingLastPathComponent()
    for _ in 0..<14 {
        let samples = url.appendingPathComponent("samples")
        let marker = samples.appendingPathComponent("LT/expected")
        if FileManager.default.fileExists(atPath: marker.path) {
            return samples.path
        }
        guard url.path != "/" else { break }
        url.deleteLastPathComponent()
    }

    let cwd = FileManager.default.currentDirectoryPath
    let cwdCandidates = [
        "\(cwd)/samples",
        URL(fileURLWithPath: cwd).deletingLastPathComponent().appendingPathComponent("samples").path,
        URL(fileURLWithPath: cwd).deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("samples").path,
    ]
    for path in cwdCandidates where FileManager.default.fileExists(atPath: "\(path)/LT/expected") {
        return path
    }

    return cwdCandidates[0]
}

