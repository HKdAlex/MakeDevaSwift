    // MARK: - Test Helper
    
    /// Run a parity test for a specific sample file
    /// - Parameters:
    ///   - directory: The subdirectory under samples/ (e.g., "LT" or "HU")
    ///   - filePrefix: The file prefix (e.g., "LTS301XT")
    private func runParityTest(directory: String, filePrefix: String) async throws {
        let samplesPath = Self.samplesPath
        let dirPath = "\(samplesPath)/\(directory)"
        let expectedPath = "\(dirPath)/expected"
        
        // Find the input file (may have different extensions like .H33, .H67, etc.)
        let inputFile = try findFile(in: dirPath, withPrefix: filePrefix)
        let inputFileName = (inputFile as NSString).lastPathComponent
        let expectedFile = "\(expectedPath)/\(inputFileName).expected"
        
        // Verify files exist
        guard FileManager.default.fileExists(atPath: inputFile) else {
            Issue.record(Comment(rawValue: "Input file not found: \(inputFile)"))
            return
        }
        guard FileManager.default.fileExists(atPath: expectedFile) else {
            Issue.record(Comment(rawValue: "Expected output file not found: \(expectedFile)"))
            return
        }
        
        // Create temporary output file
        let tempDir = FileManager.default.temporaryDirectory
        let outputFile = tempDir.appendingPathComponent("\(filePrefix)_swift_output.txt").path
        
        // Run Swift conversion with default options
        do {
            let options = CLIOptions()
            try FileProcessor.processFile(input: inputFile, output: outputFile, options: options)
        } catch {
            Issue.record(Comment(rawValue: "Swift conversion failed: \(error)"))
            return
        }
        
        // Compare outputs
        let expectedData = try Data(contentsOf: URL(fileURLWithPath: expectedFile))
        let actualData = try Data(contentsOf: URL(fileURLWithPath: outputFile))
        
        if expectedData != actualData {
            // Find first difference for debugging
            let (lineNum, expectedLine, actualLine) = findFirstDifference(
                expected: expectedData, actual: actualData)
            
            Issue.record(Comment(rawValue: """
                Output mismatch for \(filePrefix):
                First difference at line \(lineNum):
                  Expected: \(expectedLine)
                  Actual:   \(actualLine)
                Expected size: \(expectedData.count) bytes
                Actual size: \(actualData.count) bytes
                """))
        }
        
        // Clean up temp file
        try? FileManager.default.removeItem(atPath: outputFile)
        
        #expect(expectedData == actualData, "Output should match expected C output for \(filePrefix)")
    }
    
    /// Find a file in a directory with a given prefix
    private func findFile(in directory: String, withPrefix prefix: String) throws -> String {
        let fm = FileManager.default
        let contents = try fm.contentsOfDirectory(atPath: directory).sorted()
        for name in contents where name != ".DS_Store" {
            let full = "\(directory)/\(name)"
            var isDir: ObjCBool = false
            guard fm.fileExists(atPath: full, isDirectory: &isDir), !isDir.boolValue else { continue }
            if name.hasPrefix(prefix) { return full }
        }
        throw NSError(
            domain: "FunctionalParityTests", code: 1,
            userInfo: [NSLocalizedDescriptionKey: "No file found with prefix \(prefix) in \(directory)"])
    }
    
    /// Find the first line that differs between expected and actual output
    private func findFirstDifference(expected: Data, actual: Data) -> (lineNum: Int, expectedLine: String, actualLine: String) {
        let expectedLines = String(data: expected, encoding: .isoLatin1)?.components(separatedBy: .newlines) ?? []
        let actualLines = String(data: actual, encoding: .isoLatin1)?.components(separatedBy: .newlines) ?? []
        
        let maxLines = max(expectedLines.count, actualLines.count)
        for i in 0..<maxLines {
            let expectedLine = i < expectedLines.count ? expectedLines[i] : "<missing>"
            let actualLine = i < actualLines.count ? actualLines[i] : "<missing>"
            
            if expectedLine != actualLine {
                // Truncate long lines for readability
                let truncatedExpected = expectedLine.count > 80 ? String(expectedLine.prefix(80)) + "..." : expectedLine
                let truncatedActual = actualLine.count > 80 ? String(actualLine.prefix(80)) + "..." : actualLine
                return (i + 1, truncatedExpected, truncatedActual)
            }
        }
        
        return (0, "", "")
    }
}

// MARK: - Batch Test for CI/CD

/// A single test that runs all parity checks - useful for quick CI validation
struct FunctionalParityBatchTests {
    
    @Test("All samples pass functional parity")
    func testAllSamplesParity() async throws {
        var failures: [String] = []
        let samplesPath = resolveParitySamplesDirectory()

        // Test all LT files
        let ltFiles = ["LTS301XT", "LTS302XT", "LTS303XT", "LTS304XT", "LTS305XT",
                       "LTS306XT", "LTS307XT", "LTS308XT", "LTS309XT", "LTS310XT",
                       "LTS311XT", "LTS312XT", "LTS313XT", "LTS314XT", "LTS315XT",
                       "LTS316XT", "LTS317XT", "LTS318XT", "LTS319XT", "LTS320XT",
                       "LTS321XT", "LTS322XT", "LTS323XT", "LTS324XT", "LTS325XT",
                       "LTS326XT", "LTS327XT", "LTS328XT", "LTS329XT", "LTS330XT",
                       "LTS331XT", "LTS332XT", "LTS333XT"]

        // Test all HU files
        let huFiles = ["HUBG01XT", "HUBG02XT", "HUBG03XT", "HUBG04XT", "HUBG05XT",
                       "HUBG06XT", "HUBG07XT", "HUBG08XT", "HUBG09XT", "HUBG10XT",
                       "HUBG11XT", "HUBG12XT", "HUBG13XT", "HUBG14XT", "HUBG15XT",
                       "HUBG16XT", "HUBG17XT", "HUBG18XT"]

        let allJobs: [(dir: String, prefix: String)] =
            ltFiles.map { ("LT", $0) } + huFiles.map { ("HU", $0) }

        let maxConcurrent = 6
        var iterator = allJobs.makeIterator()
        await withTaskGroup(of: String?.self) { group in
            func addNext() {
                if let job = iterator.next() {
                    group.addTask {
                        FunctionalParityBatchTests.runQuickParityCheck(
                            samplesPath: samplesPath, directory: job.dir, filePrefix: job.prefix)
                    }
                }
            }
            for _ in 0..<min(maxConcurrent, allJobs.count) { addNext() }
            while let failure = await group.next() {
                if let failure { failures.append(failure) }
                addNext()
            }
        }
        
        if !failures.isEmpty {
            let failureMessage = "Parity failures:\n" + failures.joined(separator: "\n")
            Issue.record(Comment(rawValue: failureMessage))
        }
        
        #expect(failures.isEmpty, "All \(ltFiles.count + huFiles.count) sample files should pass parity check")
        print("✅ All \(ltFiles.count + huFiles.count) sample files passed parity check")
    }
    
    /// Quick parity check that returns `"id: reason"` or nil on success
    private nonisolated static func runQuickParityCheck(
        samplesPath: String, directory: String, filePrefix: String
    ) -> String? {
        let dirPath = "\(samplesPath)/\(directory)"
        let expectedPath = "\(dirPath)/expected"
        
        // Find input file
        guard let inputFile = try? findFile(in: dirPath, withPrefix: filePrefix) else {
            return "\(filePrefix): input file not found"
        }
        
        let inputFileName = (inputFile as NSString).lastPathComponent
        let expectedFile = "\(expectedPath)/\(inputFileName).expected"
        
        guard FileManager.default.fileExists(atPath: expectedFile) else {
            return "\(filePrefix): expected file not found"
        }
        
        // Create temp output
        let tempDir = FileManager.default.temporaryDirectory
        let outputFile = tempDir.appendingPathComponent("\(filePrefix)_test.txt").path
        
        // Run conversion with default options
        do {
            let options = CLIOptions()
            try FileProcessor.processFile(input: inputFile, output: outputFile, options: options)
        } catch {
            return "\(filePrefix): conversion error: \(error)"
        }
        
        // Compare
        guard let expectedData = try? Data(contentsOf: URL(fileURLWithPath: expectedFile)),
              let actualData = try? Data(contentsOf: URL(fileURLWithPath: outputFile)) else {
            return "\(filePrefix): failed to read output files"
        }
        
        try? FileManager.default.removeItem(atPath: outputFile)
        
        if expectedData != actualData {
            return
                "\(filePrefix): output mismatch (\(expectedData.count) vs \(actualData.count) bytes)"
        }

        return nil
    }

    private nonisolated static func findFile(in directory: String, withPrefix prefix: String) throws
        -> String
    {
        let fm = FileManager.default
        let contents = try fm.contentsOfDirectory(atPath: directory).sorted()
        for name in contents where name != ".DS_Store" {
            let full = "\(directory)/\(name)"
            var isDir: ObjCBool = false
            guard fm.fileExists(atPath: full, isDirectory: &isDir), !isDir.boolValue else { continue }
            if name.hasPrefix(prefix) { return full }
        }
        throw NSError(domain: "Test", code: 1, userInfo: nil)
    }
